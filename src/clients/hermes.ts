import path from "node:path";
import { commandExists } from "../project.js";
import { pathExists, readText } from "../io.js";
import { readTemplate } from "../templates.js";
import type { ClientStatus, InstallManifest } from "../types.js";
import type { ClientAdapter, ManagedPath } from "./client.js";
import { removeOwnedFile, writeOwnedFile } from "./shared.js";

const PLUGIN_FILES = ["plugin.yaml", "__init__.py"] as const;
const PLUGIN_PATH = ".hermes/plugins/prolong";

export class HermesAdapter implements ClientAdapter {
  readonly name = "hermes" as const;

  constructor(private readonly root: string, private readonly manifest: InstallManifest | null) {}

  async detect(): Promise<boolean> {
    return await commandExists("hermes") || await pathExists(path.join(this.root, ".hermes"));
  }

  async install(): Promise<ManagedPath[]> {
    const managed: ManagedPath[] = [];
    for (const file of PLUGIN_FILES) {
      const target = `${PLUGIN_PATH}/${file}`;
      const content = await readTemplate(`clients/hermes/${file}`);
      await writeOwnedFile(this.root, target, content, this.manifest, "Generated by PRO-LONG");
      managed.push({ path: target, mode: "owned" });
    }
    return managed;
  }

  async status(): Promise<ClientStatus> {
    const detected = await this.detect();
    const contents = await Promise.all(PLUGIN_FILES.map((file) => readText(path.join(this.root, PLUGIN_PATH, file))));
    const installed = contents.every((content) => content?.includes("Generated by PRO-LONG") === true);
    return {
      name: this.name,
      detected,
      installed,
      healthy: installed,
      detail: installed ? "project plugin installed; Hermes activation and skill trust are not checked" : "project plugin files are missing",
    };
  }

  async uninstall(manifest: InstallManifest | null): Promise<string[]> {
    const warnings: string[] = [];
    for (const file of PLUGIN_FILES) {
      const warning = await removeOwnedFile(this.root, `${PLUGIN_PATH}/${file}`, manifest, await readTemplate(`clients/hermes/${file}`));
      if (warning !== null) warnings.push(warning);
    }
    return warnings;
  }
}
